"""신고 문장의 개인정보 가리기 — 전화번호·카드번호·주민등록번호·여권번호·이메일을 저장·AI 전송 전에 가림.

신고 폼은 '적지 마세요'라고 안내하지만 들어오면 그대로 DB·백업·Gemini로 갔음(외부 리뷰 지적, 11/15).
물건을 찾는 데 필요 없는 정보라 가려도 검색에 지장 없음. 날짜·모델명(A2848)·금액을 잘못 가리지 않게 좁게 잡음.
"""

from __future__ import annotations

import re

_RULES: list[tuple[str, re.Pattern]] = [
    ("[이메일]", re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")),
    ("[주민번호]", re.compile(r"(?<!\d)\d{6}\s?-\s?[1-8]\d{6}(?!\d)")),
    ("[카드번호]", re.compile(r"(?<!\d)\d{4}(?:[\s-]?\d{4}){2}[\s-]?\d{3,4}(?!\d)")),
    ("[전화번호]", re.compile(r"(?<![\d+])(?:\+82[\s-]?|0)1[016789][\s.-]?\d{3,4}[\s.-]?\d{4}(?!\d)")),   # 휴대전화
    ("[전화번호]", re.compile(r"(?<![\d+])(?:\+82[\s-]?|0)(?:2|[3-6][1-5]|70)-\d{3,4}-\d{4}(?!\d)")),     # 일반전화(하이픈 있을 때만)
    ("[여권번호]", re.compile(r"(?<![A-Za-z0-9])[MSRODG]\d{3}[A-Z]?\d{4,5}(?![A-Za-z0-9])")),
]


def mask(text: str | None) -> tuple[str, int]:
    """(가린 문장, 가린 개수). 빈 값은 그대로."""
    t, n = text or "", 0
    for label, rx in _RULES:
        t, k = rx.subn(label, t)
        n += k
    return t, n
